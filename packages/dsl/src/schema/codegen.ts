/**
 * `SchemaRegistry` codegen (spec §10, §15.7).
 *
 * Renders a loaded `SchemaSet` as a `.d.ts` module augmentation so the editor can
 * complete workflow data types. Every `$ref` becomes `SchemaRegistry["<key>"]`,
 * which makes recursive schemas free. Output is sorted, hence idempotent.
 */

import type { JsonSchema } from "../surface/header.js";
import type { SchemaSet } from "./load.js";

type Obj = Record<string, unknown>;
const isObj = (v: unknown): v is Obj => typeof v === "object" && v !== null && !Array.isArray(v);

const DEFINITIONS_PREFIX = "#/definitions/";
const lit = (v: unknown): string => JSON.stringify(v) ?? "unknown";
/** A literal type; only string, finite number, boolean and null are valid TS literal types. */
const primLit = (v: unknown): string =>
  v === null || typeof v === "string" || typeof v === "boolean" || (typeof v === "number" && Number.isFinite(v))
    ? lit(v)
    : "unknown";
const paren = (t: string): string => (/[|&]/.test(t) ? `(${t})` : t);

function ofType(type: string, s: Obj): string {
  switch (type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${paren(s.items === undefined || Array.isArray(s.items) ? "unknown" : render(s.items))}[]`;
    case "object":
      return objectType(s);
    default:
      return "unknown";
  }
}

function objectType(s: Obj): string {
  const props = isObj(s.properties) ? s.properties : {};
  const required = new Set(Array.isArray(s.required) ? s.required : []);
  const members = Object.keys(props)
    .sort()
    .map((k) => `${lit(k)}${required.has(k) ? "" : "?"}: ${render(props[k])}`);
  const extra = s.additionalProperties;
  if (extra === false) return members.length ? `{ ${members.join("; ")} }` : "Record<string, never>";
  if (extra === undefined || extra === true) return `{ ${[...members, "[k: string]: unknown"].join("; ")} }`;
  const index = `{ [k: string]: ${render(extra)} }`;
  return members.length ? `{ ${members.join("; ")} } & ${index}` : index;
}

function render(schema: unknown): string {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  if (!isObj(schema)) return "unknown";
  const s = schema;

  if (typeof s.$ref === "string" && s.$ref.startsWith(DEFINITIONS_PREFIX)) {
    return `SchemaRegistry[${lit(s.$ref.slice(DEFINITIONS_PREFIX.length))}]`;
  }
  if ("const" in s) return primLit(s.const);
  if (Array.isArray(s.enum)) return s.enum.length ? [...new Set(s.enum.map(primLit))].join(" | ") : "never";

  const parts: string[] = [];
  if (typeof s.type === "string") parts.push(ofType(s.type, s));
  else if (Array.isArray(s.type) && s.type.length === 0) parts.push("unknown");
  else if (Array.isArray(s.type)) parts.push(paren([...new Set(s.type.map((t) => ofType(String(t), s)))].join(" | ")));
  else if (isObj(s.properties)) parts.push(objectType(s));

  for (const kw of ["oneOf", "anyOf"] as const) {
    const alts = s[kw];
    if (Array.isArray(alts) && alts.length) parts.push(paren(alts.map((a) => paren(render(a))).join(" | ")));
  }
  if (Array.isArray(s.allOf) && s.allOf.length) parts.push(...s.allOf.map((a) => paren(render(a))));

  return parts.length ? parts.join(" & ") : "unknown";
}

/** Renders the `.d.ts` that fills `SchemaRegistry` for every key in `set`. */
export function generateRegistry(set: SchemaSet): string {
  const lines = [...set.byKey.keys()].sort().map((k) => `    ${lit(k)}: ${render(set.byKey.get(k) as JsonSchema)};`);
  return [
    "// Generated by `aflow types`. Do not edit.",
    "export {};",
    "",
    'declare module "@aflow/dsl" {',
    "  interface SchemaRegistry {",
    ...lines,
    "  }",
    "}",
    "",
  ].join("\n");
}
